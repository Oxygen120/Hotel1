create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = public, auth, pg_temp
as $$
  select exists (
    select 1 from public.staff_users s
    where s.user_id = (select auth.uid()) and s.is_active = true
  );
$$;

