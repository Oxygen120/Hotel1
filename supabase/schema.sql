create or replace function public.create_order(
  p_table_token text,
  p_customer_name text,
  p_customer_phone text,
  p_marketing_opt_in boolean,
  p_customer_note text,
  p_items jsonb,
  p_order_type text default 'dine_in',
  p_delivery_details jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_table_id uuid;
  v_order_type text := coalesce(p_order_type, 'dine_in');
  v_order_id uuid;
  v_order_number bigint;
  v_public_token uuid;
  v_item jsonb;
  v_menu_item public.menu_items%rowtype;
  v_qty integer;
  v_item_count integer := 0;
  v_subtotal numeric(10, 2) := 0;
  v_tax_percent numeric(6, 3) := 0;
  v_tax numeric(10, 2) := 0;
  v_total numeric(10, 2) := 0;
  v_discount_percent numeric(5, 2) := 0;
  v_unit_discount numeric(10, 2) := 0;
  v_discount_total numeric(10, 2) := 0;
  v_is_accepting_orders boolean;
  v_delivery_enabled boolean;
  v_delivery_city text;
  v_delivery_areas text[];
  v_delivery_fee numeric(10, 2) := 0;
  v_input_city text;
  v_input_area text;
  v_input_address text;
  v_input_postal_code text;
begin
  select coalesce(s.is_accepting_orders, true) into v_is_accepting_orders
  from public.restaurant_settings s where s.id = true;
  if coalesce(v_is_accepting_orders, true) = false then
    raise exception 'The restaurant is not accepting orders right now.' using errcode = '22023';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'Choose between 1 and 30 menu items.' using errcode = '22023';
  end if;
  if jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 30 then
    raise exception 'Choose between 1 and 30 menu items.' using errcode = '22023';
  end if;
  if v_order_type not in ('dine_in', 'delivery') then
    raise exception 'Invalid order type.' using errcode = '22023';
  end if;
  if v_order_type = 'dine_in' then
    select t.id into v_table_id from public.dining_tables t
    where t.qr_token = p_table_token and t.is_active = true;
    if v_table_id is null then
      raise exception 'This table QR is not active. Please ask a team member.' using errcode = '22023';
    end if;
  elsif v_order_type = 'delivery' then
    select coalesce(s.is_delivery_enabled, false), coalesce(s.delivery_city, ''), coalesce(s.delivery_areas, '{}'::text[]), coalesce(s.delivery_fee, 0)
    into v_delivery_enabled, v_delivery_city, v_delivery_areas, v_delivery_fee
    from public.restaurant_settings s where s.id = true;
    if not coalesce(v_delivery_enabled, false) or length(trim(v_delivery_city)) = 0 or cardinality(v_delivery_areas) = 0 then
      raise exception 'Home delivery is not available right now.' using errcode = '22023';
    end if;
    if p_delivery_details is null or jsonb_typeof(p_delivery_details) <> 'object' then
      raise exception 'Enter a delivery address in a supported area.' using errcode = '22023';
    end if;
    v_input_city := nullif(trim(p_delivery_details->>'city'), '');
    v_input_area := nullif(trim(p_delivery_details->>'area'), '');
    v_input_address := nullif(trim(p_delivery_details->>'address'), '');
    v_input_postal_code := nullif(trim(p_delivery_details->>'postal_code'), '');
    if lower(coalesce(v_input_city, '')) <> lower(trim(v_delivery_city)) then
      raise exception 'Delivery is only available in %.', v_delivery_city using errcode = '22023';
    end if;
    if v_input_area is null or not exists (select 1 from unnest(v_delivery_areas) as zones(area) where lower(trim(area)) = lower(v_input_area)) then
      raise exception 'Choose one of the supported delivery areas.' using errcode = '22023';
    end if;
    if v_input_address is null or length(v_input_address) > 300 or length(coalesce(v_input_postal_code, '')) > 12 then
      raise exception 'Enter a valid delivery address.' using errcode = '22023';
    end if;
    select trim(area) into v_input_area from unnest(v_delivery_areas) as zones(area) where lower(trim(area)) = lower(v_input_area) limit 1;
    v_input_city := trim(v_delivery_city);
  end if;
  if length(coalesce(p_customer_name, '')) > 80 or length(coalesce(p_customer_phone, '')) > 25 or length(coalesce(p_customer_note, '')) > 400 then
    raise exception 'Name or order note is too long.' using errcode = '22023';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if jsonb_typeof(v_item) <> 'object' or not (v_item ? 'menu_item_id') or not (v_item ? 'quantity') then
      raise exception 'Every item needs a menu item and quantity.' using errcode = '22023';
    end if;
    v_qty := (v_item->>'quantity')::integer;
    if v_qty is null or v_qty < 1 or v_qty > 20 then
      raise exception 'Each quantity must be between 1 and 20.' using errcode = '22023';
    end if;
    select m.* into v_menu_item from public.menu_items m
    join public.menu_categories c on c.id = m.category_id and c.is_active = true
    where m.id = (v_item->>'menu_item_id')::uuid and m.is_available = true;
    if not found then
      raise exception 'A selected item is unavailable. Refresh the menu and try again.' using errcode = '22023';
    end if;
    v_discount_percent := coalesce(v_menu_item.discount_percent, 0);
    v_unit_discount := round(v_menu_item.price * v_discount_percent / 100, 2);
    v_subtotal := v_subtotal + ((v_menu_item.price - v_unit_discount) * v_qty);
    v_discount_total := v_discount_total + (v_unit_discount * v_qty);
    v_item_count := v_item_count + 1;
  end loop;
  if v_item_count <> jsonb_array_length(p_items) then
    raise exception 'One or more items could not be added.' using errcode = '22023';
  end if;

  select coalesce(s.tax_percent, 0) into v_tax_percent
  from public.restaurant_settings s where s.id = true;
  v_tax := round(v_subtotal * coalesce(v_tax_percent, 0) / 100, 2);
  v_total := v_subtotal + v_tax + v_delivery_fee;

  insert into public.orders (table_id, order_type, customer_name, customer_phone, marketing_opt_in, customer_note, subtotal, discount_total, tax_total, delivery_city, delivery_area, delivery_address, delivery_postal_code, delivery_fee, grand_total)
  values (v_table_id, v_order_type, nullif(trim(p_customer_name), ''), nullif(trim(p_customer_phone), ''), coalesce(p_marketing_opt_in, false) and nullif(trim(p_customer_phone), '') is not null, nullif(trim(p_customer_note), ''), v_subtotal, v_discount_total, v_tax, v_input_city, v_input_area, v_input_address, v_input_postal_code, v_delivery_fee, v_total)
  returning id, order_number, public_token into v_order_id, v_order_number, v_public_token;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_qty := (v_item->>'quantity')::integer;
    select m.* into v_menu_item from public.menu_items m
    join public.menu_categories c on c.id = m.category_id and c.is_active = true
    where m.id = (v_item->>'menu_item_id')::uuid and m.is_available = true;
    v_discount_percent := coalesce(v_menu_item.discount_percent, 0);
    v_unit_discount := round(v_menu_item.price * v_discount_percent / 100, 2);
    insert into public.order_items (order_id, menu_item_id, name, price_at_order, list_price_at_order, discount_percent_at_order, discount_amount, is_today_special_at_order, quantity, is_vegetarian)
    values (v_order_id, v_menu_item.id, v_menu_item.name, v_menu_item.price - v_unit_discount, v_menu_item.price, v_discount_percent, v_unit_discount * v_qty, v_menu_item.is_today_special, v_qty, v_menu_item.is_vegetarian);
  end loop;

  return jsonb_build_object(
    'id', v_order_id,
    'order_number', v_order_number,
    'public_token', v_public_token,
    'subtotal', v_subtotal,
    'discount_total', v_discount_total,
    'tax_total', v_tax,
    'delivery_fee', v_delivery_fee,
    'grand_total', v_total,
    'status', 'pending'
  );
end;
$$;

